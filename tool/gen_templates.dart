// Writes lib/src/create/templates.g.dart from templates/ and pubspec.yaml.
//
//   dart run tool/gen_templates.dart
//
// `dart_tui create` must not read files at runtime (that breaks under
// `dart compile exe` and some global installs), so the starters are Dart
// string constants. test/create_templates_test.dart fails when this file is
// out of date.
//
// In templates/<starter>/, `__name__` is the package name, a `.tmpl` suffix is
// dropped (it keeps pub and the analyzer from treating the starter's
// pubspec.yaml and analysis_options.yaml as real ones) and `gitignore`
// becomes `.gitignore`.
import 'dart:io';

const output = 'lib/src/create/templates.g.dart';

void main() {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_templates.dart from templates/. '
        'Do not edit.')
    ..writeln()
    ..writeln('/// The version of dart_tui in pubspec.yaml.')
    ..writeln("const packageVersion = '${readVersion()}';")
    ..writeln()
    ..writeln('/// Each starter\'s files: path to content. `__name__` is the '
        'package name.')
    ..writeln('const starterFiles = <String, Map<String, String>>{');
  readTemplates().forEach((starter, files) {
    out.writeln("  '$starter': {");
    files.forEach((path, content) {
      if (content.contains("'''") || content.endsWith("'")) {
        throw StateError("templates/$starter/$path: ''' cannot be embedded");
      }
      out.writeln("    '$path': r'''\n$content''',");
    });
    out.writeln('  },');
  });
  out.writeln('};');
  File(output).writeAsStringSync('$out');
  final format = Process.runSync(Platform.resolvedExecutable, [
    'format',
    output,
  ]);
  if (format.exitCode != 0) throw StateError('${format.stderr}');
  stdout.writeln('Wrote $output');
}

/// The version line of pubspec.yaml.
String readVersion() => RegExp(r'^version:\s*(\S+)', multiLine: true)
    .firstMatch(File('pubspec.yaml').readAsStringSync())!
    .group(1)!;

/// templates/: starter name to (output path to content), sorted.
Map<String, Map<String, String>> readTemplates() {
  final starters = <String, Map<String, String>>{};
  final dirs = Directory('templates').listSync().whereType<Directory>().toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  for (final dir in dirs) {
    final files = <String, String>{};
    for (final file in dir.listSync(recursive: true).whereType<File>()) {
      var path = file.path
          .substring(dir.path.length + 1)
          .replaceAll(Platform.pathSeparator, '/');
      if (path.endsWith('.tmpl')) path = path.substring(0, path.length - 5);
      if (path == 'gitignore') path = '.gitignore';
      files[path] = file.readAsStringSync().replaceAll('\r\n', '\n');
    }
    starters[dir.uri.pathSegments.lastWhere((s) => s.isNotEmpty)] = {
      for (final path in files.keys.toList()..sort()) path: files[path]!,
    };
  }
  return starters;
}
